#!/usr/bin/env python3
"""Regenerates Packages/com.mckrill.avbd/Tests/Reference/UpstreamGolden.cs from the upstream C++ solver.

Usage:
    OUT=$(Tools/UpstreamGolden/build.sh)
    python3 Tools/UpstreamGolden/generate_golden.py "$OUT/driver_up" \
        Packages/com.mckrill.avbd/Tests/Reference/UpstreamGolden.cs

For every (scene, step) the upstream solver is run twice: as is, and with every dynamic body nudged by
1e-6 in x. The difference between the two is a measure of how much a one-ulp-scale change is amplified
by the solver on that scene, and the test tolerance is 8x that difference (with a floor). That makes
the tolerance as tight as the scene's own numerical sensitivity allows.
"""
import subprocess
import sys

PLAN = {
    "ground": [1, 10, 30, 60, 120],
    "stack": [1, 10, 30, 60, 120],
    "rope": [1, 10, 30, 60],
    "spring": [1, 10, 30, 60, 120],
}
NUDGE = "1e-6"
MARGIN = 8.0
FLOOR = (2e-4, 1e-4, 5e-4)  # position, rotation, velocity


def run(driver, args):
    out = subprocess.run([driver] + args, capture_output=True, text=True, check=True).stdout.splitlines()
    res, cur = {}, None
    for line in out:
        t = line.split()
        if t[0] == "S":
            cur = int(t[2])
            res[cur] = []
        else:
            res[cur].append(t[1:])
    return res


def literal(text):
    if "." not in text and "e" not in text and "n" not in text:
        text += ".0"
    return text + "f"


def spread(a, b, lo, hi):
    return max(max(abs(x - y) for x, y in zip(p[lo:hi], q[lo:hi])) for p, q in zip(a, b))


def main():
    driver, out_path = sys.argv[1], sys.argv[2]
    cases = []
    for scene, steps in PLAN.items():
        golden = run(driver, ["golden", scene] + [str(s) for s in steps])
        nudged = run(driver, ["jitter", scene, NUDGE] + [str(s) for s in steps])
        for step in steps:
            g = [[float(v) for v in b] for b in golden[step]]
            j = [[float(v) for v in b] for b in nudged[step]]
            tol = (
                max(FLOOR[0], MARGIN * spread(g, j, 0, 3)),
                max(FLOOR[1], MARGIN * spread(g, j, 3, 7)),
                max(FLOOR[2], MARGIN * spread(g, j, 7, 13)),
            )
            flat = [literal(v) for b in golden[step] for v in b]
            cases.append((scene, step, len(golden[step]), tol, flat))

    w = []
    w.append("// <auto-generated>")
    w.append("// Golden trajectories captured from the upstream avbd-demo3d C++ solver (MIT, Chris Giles).")
    w.append("// Built headless with g++ -O2 -ffp-contract=off, scenes from upstream scenes.h, default solver params.")
    w.append("// Per body, 13 floats: position (3), rotation x y z w (4), linear velocity (3), angular velocity (3),")
    w.append("// bodies in creation order. Tolerances are 8x the divergence measured when every dynamic body was")
    w.append("// nudged by 1e-6 in x in the C++ solver (a proxy for cross-implementation rounding), with floors.")
    w.append("// Regenerate with Tools/UpstreamGolden/generate_golden.py (see Tools/UpstreamGolden/README.md).")
    w.append("// </auto-generated>")
    w.append("namespace McKrill.Avbd.Tests")
    w.append("{")
    w.append("    public readonly struct UpstreamGoldenCase")
    w.append("    {")
    w.append("        public readonly string Scene;")
    w.append("        public readonly int Step;")
    w.append("        public readonly int BodyCount;")
    w.append("        public readonly float PositionTolerance;")
    w.append("        public readonly float RotationTolerance;")
    w.append("        public readonly float VelocityTolerance;")
    w.append("        public readonly float[] State;")
    w.append("")
    w.append("        public UpstreamGoldenCase(string scene, int step, int bodyCount, float posTol, float rotTol, float velTol, float[] state)")
    w.append("        {")
    w.append("            Scene = scene; Step = step; BodyCount = bodyCount;")
    w.append("            PositionTolerance = posTol; RotationTolerance = rotTol; VelocityTolerance = velTol; State = state;")
    w.append("        }")
    w.append("")
    w.append('        public override string ToString() => $"{Scene}@{Step}";')
    w.append("    }")
    w.append("")
    w.append("    public static class UpstreamGolden")
    w.append("    {")
    w.append("        public static readonly UpstreamGoldenCase[] Cases =")
    w.append("        {")
    for scene, step, n, (tp, tq, tv), flat in cases:
        w.append(f'            new UpstreamGoldenCase("{scene}", {step}, {n}, {tp:.1e}f, {tq:.1e}f, {tv:.1e}f, new float[]')
        w.append("            {")
        for i in range(0, len(flat), 13):
            w.append("                " + ", ".join(flat[i:i + 13]) + ",")
        w.append("            }),")
    w.append("        };")
    w.append("    }")
    w.append("}")
    open(out_path, "w").write("\n".join(w) + "\n")
    print(len(cases), "cases written to", out_path)


main()
